/* Helper: look up an article by its slug */
function getArticleBySlug(slug) {
    return articles.find(a => a.slug === slug);
}

/* Helper: featured articles, in the order they're defined */
function getFeaturedArticles() {
    return articles.filter(a => a.featured);
}

/* Helper: non-featured articles, newest first */
function getLatestArticles() {
    return articles
        .filter(a => !a.featured)
        .sort((a, b) => new Date(b.date) - new Date(a.date));
}

/* Helper: up to `limit` other articles, same category first, then newest */
function getRelatedArticles(article, limit = 3) {

    const sameCategory = articles.filter(a =>
        a.category === article.category && a.id !== article.id
    );

    const others = articles
        .filter(a => a.id !== article.id && !sameCategory.includes(a))
        .sort((a, b) => new Date(b.date) - new Date(a.date));

    return [...sameCategory, ...others].slice(0, limit);

}

/* Helper: "2026-07-25" -> "July 25, 2026" */
function formatArticleDate(iso) {
    return new Date(iso + "T00:00:00").toLocaleDateString(undefined, {
        year: "numeric", month: "long", day: "numeric"
    });
}
